def eval_gat(states, model_path, device):
    """
    Run our GAT model on given states; return list of sum-rates (Mbps).
    """
    # model hyperparams should match the saved checkpoint
    model = GATScheduler(
        raw_node_dim=1,
        mlp_hidden_dims=[32, 32],
        embed_node_dim=32,
        edge_dim=1,
        gat_out_dim=48,
        num_heads=4,
        T_iterations=4,
        schedule_hidden_dim=32,
    ).to(device)

    if os.path.exists(model_path):
        state_dict = torch.load(model_path, map_location=device)
        model.load_state_dict(state_dict)
        print(f"[GAT] Loaded checkpoint: {model_path}")
    else:
        print(f"[GAT] Warning: checkpoint not found, using random init: {model_path}")

    model.eval()
    sum_rates = []
    with torch.no_grad():
        for state in states:
            x = state.vertex_features.to(device)
            edge_index = state.edge_index.to(device)
            edge_weights = state.edge_weights.to(device)
            pi, _ = model(x, edge_index, edge_weights, use_ste=False)
            pi_hard = (pi > 0.5).float()
            rates = calculate_achievable_rate(pi_hard, state, binary=True, detach_hard=True)
            sum_rates.append(rates.sum().item())
    return sum_rates


